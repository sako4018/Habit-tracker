  // ==========================================================
  // FIND SUGGESTIONS
  // ==========================================================

  List<String> _getSuggestions(String text) {
    final query = text.trim().toLowerCase();

    if (query.length < 2) {
      return [];
    }

    final List<String> suggestions = [];

    for (final entry in _emojiSuggestions.entries) {
      if (query.contains(entry.key) ||
          entry.key.contains(query)) {
        for (final emoji in entry.value) {
          if (!suggestions.contains(emoji)) {
            suggestions.add(emoji);
          }
        }
      }
    }

    return suggestions.take(5).toList();
  }

  // ==========================================================
  // SUBMIT
  // ==========================================================

  void _submit() {
    final name = _nameController.text.trim();
    final emoji = _emojiController.text.trim();

    if (name.isEmpty) {
      setState(() {
        _error = 'Въведи име на навика';
      });
      return;
    }

    // Емоджито вече НЕ е задължително.

    Navigator.pop(
      context,
      {
        'name': name,
        'emoji': emoji,
      },
    );
  }

