/// Български имена на дни и месеци и дребните правила за множествено
/// число, които приложението ползва.
///
/// Съществува, защото същите списъци стояха преписани на четири места
/// (Home, месечният heatmap, календарът на навика, годишният изглед) и
/// започнаха да се разминават.
class BgDates {
  BgDates._();

  /// Имена на месеци с главна буква — за заглавие "Септември 2026".
  static const months = [
    'Януари',
    'Февруари',
    'Март',
    'Април',
    'Май',
    'Юни',
    'Юли',
    'Август',
    'Септември',
    'Октомври',
    'Ноември',
    'Декември',
  ];

  /// Имена на месеци с малка буква — за "8 септември" в изречение.
  static const monthsLower = [
    'януари',
    'февруари',
    'март',
    'април',
    'май',
    'юни',
    'юли',
    'август',
    'септември',
    'октомври',
    'ноември',
    'декември',
  ];

  static const weekdays = [
    'понеделник',
    'вторник',
    'сряда',
    'четвъртък',
    'петък',
    'събота',
    'неделя',
  ];

  /// Еднобуквени етикети за календарна мрежа, от понеделник.
  static const weekdayLetters = ['П', 'В', 'С', 'Ч', 'П', 'С', 'Н'];

  /// "Септември 2026"
  static String monthYear(DateTime date) =>
      '${months[date.month - 1]} ${date.year}';

  /// "вторник, 8 септември"
  static String weekdayDayMonth(DateTime date) =>
      '${weekdays[date.weekday - 1]}, '
      '${date.day} ${monthsLower[date.month - 1]}';

  /// "1 ден" / "5 дни"
  static String days(int count) => '$count ${count == 1 ? 'ден' : 'дни'}';

  /// "остава 1" / "остават 5" — глаголът също се съгласува по число.
  static String remaining(int count) =>
      '${count == 1 ? 'остава' : 'остават'} $count';
}
